def calculate_gc_content(dna_sequence):
    g_count = dna_sequence.count('G')
    c_count = dna_sequence.count('C')
    total_count = len(dna_sequence)

    if total_count == 0:
        return 0

    gc_content = (g_count + c_count) / total_count * 100
    return gc_content


def parse_fasta(file_path):
    sequences = {}
    with open(file_path, 'r') as file:
        identifier = None
        sequence = []

        for line in file:
            line = line.strip()
            if line.startswith('>'):
                #Сохраняем предыдущую последовательность
                if identifier is not None:
                    sequences[identifier] = ''.join(sequence)
                identifier = line[1:]  # Убираем '>'
                sequence = []
            else:
                sequence.append(line)

        #Сохраняем последнюю последовательность
        if identifier is not None:
            sequences[identifier] = ''.join(sequence)

    return sequences


def main(file_path):
    """Основная функция для нахождения последовательности с максимальным GC-составом."""
    sequences = parse_fasta(file_path)
    max_gc_content = 0
    max_gc_id = ""

    for identifier, dna_sequence in sequences.items():
        gc_content = calculate_gc_content(dna_sequence)
        if gc_content > max_gc_content:
            max_gc_content = gc_content
            max_gc_id = identifier

    print(f"{max_gc_id}\n{max_gc_content:.6f}")

