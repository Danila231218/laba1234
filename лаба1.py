def calculate_expectation(x):
    #Вероятности рождения потомка с доминантным фенотипом
    probabilities = [1, 1, 1, 3 / 4, 1 / 2, 0]

    #Количество потомков от каждой пары
    offspring_per_pair = 2

# Расчёт математического ожидания
    expectation = sum([x[i] * probabilities[i] * offspring_per_pair for i in range(len(x))])

    return expectation
